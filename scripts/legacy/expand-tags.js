// 从文本中提取关键词（2-6字的中文词）
function extractKeywords(text) {
  if (!text) return [];
  const keywords = new Set();
  
  // 提取2-6字的连续中文字符
  const matches = text.match(/[\u4e00-\u9fa5]{2,6}/g);
  if (matches) {
    matches.forEach(word => {
      if (!STOP_WORDS.has(word) && word.length >= 2 && word.length <= 6) {
        keywords.add(word);
      }
    });
  }
  
  // 提取电话号码（3-5位数字）
  const phoneMatches = text.match(/\d{3,5}/g);
  if (phoneMatches) {
    phoneMatches.forEach(phone => {
      if (phone.startsWith('123') || phone.startsWith('96') || phone.startsWith('11') || phone.startsWith('12')) {
        keywords.add(phone);
      }
    });
  }
  
  return Array.from(keywords);
}

