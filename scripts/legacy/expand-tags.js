// 扩充每个渠道的tags
let totalAdded = 0;
let totalCleaned = 0;
allChannels.forEach(ch => {
  const existingTags = new Set(ch.tags || []);
  const originalCount = existingTags.size;
  
  // 从渠道自身信息提取关键词
  const chText = ch.name + ' ' + (ch.scope || '') + ' ' + (ch.regulator || '') + ' ' + (ch.category_l1 || '') + ' ' + (ch.category_l2 || '');
  const extractedKeywords = extractKeywords(chText);
  extractedKeywords.forEach(tag => {
    if (tag.length >= 2 && tag.length <= 6 && !STOP_WORDS.has(tag)) {
      existingTags.add(tag);
    }
  });
  
  // 添加特定渠道的补充tags
  if (CHANNEL_EXTRA_TAGS[ch.id]) {
    CHANNEL_EXTRA_TAGS[ch.id].forEach(tag => existingTags.add(tag));
  }
  
  // 清理噪声tags
  const beforeClean = existingTags.size;
  const cleanedTags = Array.from(existingTags).filter(tag => {
    if (!tag || typeof tag !== 'string') return false;
    if (tag.length > 10) return false;
    if (tag.includes('（') && tag.includes('）')) return false;
    if (tag.includes('需查询') || tag.includes('各地不同')) return false;
    if (STOP_WORDS.has(tag)) return false;
    return true;
  });
  totalCleaned += (beforeClean - cleanedTags.length);
  
  // 限制每个渠道的tags数量在8-25个之间（优先保留短词和特定补充词）
  const extraTags = CHANNEL_EXTRA_TAGS[ch.id] || [];
  const priorityTags = cleanedTags.filter(tag => 
    extraTags.includes(tag) || /^\d{3,5}$/.test(tag) || tag.length <= 4
  );
  const otherTags = cleanedTags.filter(tag => !priorityTags.includes(tag));
  const finalTags = [...priorityTags, ...otherTags].slice(0, 25);
  
  ch.tags = finalTags;
  totalAdded += (finalTags.length - originalCount);
});

