// 更新法律库
let updated = 0;
let totalArticles = 0;
laws.forEach(law => {
  const lawName = law.name || law.title || '';
  if (lawArticlesBatch4[lawName]) {
    const articles = lawArticlesBatch4[lawName].map((content, index) => ({
      id: law.id + '_art_' + String(index + 1).padStart(3, '0'),
      content: content
    }));
    law.articles = articles;
    updated++;
    totalArticles += articles.length;
  }
});

// 写回文件
const content = 'module.exports = ' + JSON.stringify(laws, null, 2) + ';\n';
fs.writeFileSync(lawsPath, content, 'utf8');

console.log('更新了', updated, '部法律的条款');
console.log('共添加', totalArticles, '条条款');
