// 检查是否已存在，避免重复
const existingIds = new Set(laws.map(l => l.id));
const existingNames = new Set(laws.map(l => l.name || l.title));

let added = 0;
newLaws.forEach(law => {
  if (!existingIds.has(law.id) && !existingNames.has(law.name)) {
    laws.push(law);
    added++;
  }
});

// 写回文件
const content = 'module.exports = ' + JSON.stringify(laws, null, 2) + ';\n';
fs.writeFileSync(lawsPath, content, 'utf8');

