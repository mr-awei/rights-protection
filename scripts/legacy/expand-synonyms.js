// 读取当前config.js，找到synonyms对象并合并
// 简单方法：直接在synonyms对象的最后一个条目后插入新条目
const lines = content.split('\n');
let synonymsStart = -1;
let synonymsEnd = -1;
let braceCount = 0;
let inSynonyms = false;

for (let i = 0; i < lines.length; i++) {
  if (lines[i].includes('"synonyms"')) {
    synonymsStart = i;
    inSynonyms = true;
    braceCount = 0;
  }
  if (inSynonyms) {
    for (const char of lines[i]) {
      if (char === '{') braceCount++;
      if (char === '}') braceCount--;
    }
    if (braceCount === 0 && synonymsStart !== -1 && i > synonymsStart) {
      synonymsEnd = i;
      break;
    }
  }
}

if (synonymsStart !== -1 && synonymsEnd !== -1) {
  // 构建新的synonyms内容
  let newSynonymsContent = '  "synonyms": {\n';

  // 先复制原有条目（去掉首尾的括号和引号）
  for (let i = synonymsStart + 1; i < synonymsEnd; i++) {
    newSynonymsContent += lines[i] + '\n';
  }

  // 添加新条目
  const keys = Object.keys(newSynonyms);
  keys.forEach((key, index) => {
    const value = newSynonyms[key];
    const comma = index < keys.length - 1 ? ',' : '';
    newSynonymsContent += `    "${key}": "${value}"${comma}\n`;
  });

  newSynonymsContent += '  }';

  // 替换原有内容
  const newLines = [
    ...lines.slice(0, synonymsStart),
    newSynonymsContent,
    ...lines.slice(synonymsEnd + 1)
  ];

  content = newLines.join('\n');
  fs.writeFileSync(configPath, content, 'utf8');

  // 验证
  const config = require(configPath);
  const count = Object.keys(config.synonyms || {}).length;
  console.log('同义词典扩充完成！当前条目数:', count);
} else {
  console.log('未找到synonyms对象');
}
