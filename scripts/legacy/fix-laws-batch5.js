let fixedCount = 0;
for (let i = 0; i < laws.length; i++) {
  const law = laws[i];
  if (fixes[law.id]) {
    const fix = fixes[law.id];
    laws[i] = {
      ...law,
      name: fix.name,
      full_name: fix.full_name,
      category: fix.category,
      article: fix.article,
      articles: fix.articles
    };
    fixedCount++;
    console.log(`已修正: ${fix.name} (${law.id})`);
  }
}

