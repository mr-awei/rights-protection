let updated = 0;
let totalArticles = 0;
laws.forEach(law => {
  const lawName = law.name || law.title || '';
  if (lawArticles[lawName]) {
    const articles = lawArticles[lawName].map((content, index) => ({
      id: law.id + '_art_' + String(index + 1).padStart(3, '0'),
      content: content
    }));
    law.articles = articles;
    // 删除旧的detailed_articles字段
    delete law.detailed_articles;
    updated++;
    totalArticles += articles.length;
  }
});

