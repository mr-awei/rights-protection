// 处理渠道分片文件
const files = [
  path.join(__dirname, '..', 'miniprogram', 'data', 'channels_part_1.js'),
  path.join(__dirname, '..', 'miniprogram', 'data', 'channels_part_2.js'),
  path.join(__dirname, '..', 'miniprogram', 'data', 'channels_part_3.js'),
];

let totalUpdated = 0;

files.forEach((filePath, fileIndex) => {
  const channels = require(filePath);
  let updated = 0;

  channels.forEach(channel => {
    const category = channel.category_user_l2 || '';
    
    // 如果有专门的法律依据，跳过
    if (channel.legal_basis && 
        channel.legal_basis.includes('反垄断法') ||
        channel.legal_basis.includes('税收违法行为') ||
        channel.legal_basis.includes('会计法') ||
        channel.legal_basis.includes('统计法') ||
        channel.legal_basis.includes('政府采购法') ||
        channel.legal_basis.includes('科研诚信') ||
        channel.legal_basis.includes('国家安全法') ||
        channel.legal_basis.includes('妇女权益保障法') ||
        channel.legal_basis.includes('公平竞争审查') ||
        channel.legal_basis.includes('电信条例')) {
      // 这些是已经有专门法律依据的，跳过
      return;
    }
    
    // 按分类匹配法律依据
    if (legalBasisByCategory[category]) {
      channel.legal_basis = legalBasisByCategory[category];
      updated++;
      totalUpdated++;
    }
  });

  // 写回文件
  const content = 'module.exports = ' + JSON.stringify(channels, null, 2) + ';\n';
  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`文件${fileIndex + 1}更新了${updated}个渠道的法律依据`);
});

console.log(`\n总计更新了${totalUpdated}个渠道的法律依据`);
