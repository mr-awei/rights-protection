for (const law of laws) {
  if (fixes[law.id]) {
    for (const article of law.articles) {
      if (fixes[law.id][article.id]) {
        article.content = fixes[law.id][article.id];
        fixedCount++;
        console.log(`已修复: ${law.name} - ${article.id}`);
      }
    }
    // 同时更新顶层article字段（如果存在）
    if (law.article && law.articles.length > 0) {
      law.article = law.articles[0].content;
    }
  }
}

