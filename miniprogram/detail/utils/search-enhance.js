/**
 * 获取汉字拼音首字母
 * @param {string} char - 单个汉字
 * @returns {string} 拼音首字母（小写），非汉字返回原字符
 */
function getPinyinInitial(char) {
  if (!char) return '';
  // 先查映射表
  if (PINYIN_INITIAL_MAP[char]) {
    return PINYIN_INITIAL_MAP[char];
  }
  // 非汉字返回原字符（小写）
  if (/[a-zA-Z0-9]/.test(char)) {
    return char.toLowerCase();
  }
  return char;
}

/**
 * 获取字符串的拼音首字母串
 * @param {string} str - 中文字符串
 * @returns {string} 拼音首字母串（小写）
 */
function getPinyinInitials(str) {
  if (!str) return '';
  let result = '';
  for (let i = 0; i < str.length; i++) {
    result += getPinyinInitial(str[i]);
  }
  return result;
}

/**
 * 计算两个字符串的编辑距离（Levenshtein Distance）
 * @param {string} a - 字符串a
 * @param {string} b - 字符串b
 * @returns {number} 编辑距离
 */
function editDistance(a, b) {
  if (!a) return b ? b.length : 0;
  if (!b) return a.length;
  
  const m = a.length;
  const n = b.length;
  
  // 创建二维数组
  const dp = [];
  for (let i = 0; i <= m; i++) {
    dp[i] = [];
    dp[i][0] = i;
  }
  for (let j = 0; j <= n; j++) {
    dp[0][j] = j;
  }
  
  // 动态规划计算
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      if (a[i - 1] === b[j - 1]) {
        dp[i][j] = dp[i - 1][j - 1];
      } else {
        dp[i][j] = Math.min(
          dp[i - 1][j] + 1,      // 删除
          dp[i][j - 1] + 1,      // 插入
          dp[i - 1][j - 1] + 1   // 替换
        );
      }
    }
  }
  
  return dp[m][n];
}

/**
 * 计算两个字符串的相似度（0-1）
 * @param {string} a - 字符串a
 * @param {string} b - 字符串b
 * @returns {number} 相似度（0-1）
 */
function similarity(a, b) {
  if (!a && !b) return 1;
  if (!a || !b) return 0;
  const maxLen = Math.max(a.length, b.length);
  if (maxLen === 0) return 1;
  const dist = editDistance(a, b);
  return 1 - dist / maxLen;
}

