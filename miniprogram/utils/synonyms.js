/**
 * 获取同义词列表
 * @param {string} keyword - 关键词
 * @returns {Array} 同义词列表（包含原词）
 */
function getSynonyms(keyword) {
  if (!keyword) return [];
  const lower = keyword.toLowerCase().trim();
  // 直接匹配
  if (SYNONYMS[lower]) {
    return [lower, ...SYNONYMS[lower]];
  }
  // 反向匹配：检查是否是某个词的同义词
  for (const [key, synonyms] of Object.entries(SYNONYMS)) {
    if (synonyms.includes(lower)) {
      return [lower, key, ...synonyms.filter(s => s !== lower)];
    }
  }
  return [lower];
}

/**
 * 扩展搜索关键词（返回所有相关关键词）
 * @param {Array} keywords - 原始关键词列表
 * @returns {Array} 扩展后的关键词列表（去重）
 */
function expandKeywords(keywords) {
  if (!keywords || keywords.length === 0) return [];
  const expanded = new Set();
  for (const kw of keywords) {
    const syns = getSynonyms(kw);
    syns.forEach(s => expanded.add(s));
  }
  return Array.from(expanded);
}

